export function apiErrorMessage(code: string, fallback: string): string {
  const map: Record<string, string> = {
    invalid_credentials: t.login.invalid,
    invalid_totp: t.login.invalidTotp,
    throttled: t.login.throttled,
    invalid_token: t.reset.invalidToken,
    network: t.common.network,
    forbidden: t.errors.forbidden,
    not_found: t.errors.notFound,
  };
  return map[code] ?? fallback;
}
